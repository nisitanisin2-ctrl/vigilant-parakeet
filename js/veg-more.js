function vegGroup(v) {
  const f = (VEG_CARE[v.n] || VEG_CARE[v.base] || {}).f;
  return { fruit: 'mi', corn: 'mi', berry: 'mi', leaf: 'ha', root: 'ne', potato: 'ne', sweet: 'ne', taro: 'ne', bean: 'mame', allium: 'negi' }[f] || 'ha';
}
